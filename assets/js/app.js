function renderProjects() {
  if (!projectsGrid) return;
  const visible = PROJECTS.filter(
    (project) => state.filter === "all" || project.cat === state.filter
  );

  if (!visible.length) {
    projectsGrid.innerHTML = `<p class="projects-empty">${t("projects.empty")}</p>`;
    projectsGrid.hidden = false;
    projectsGrid.classList.remove("has-odd");
    if (projectsListWrap) projectsListWrap.hidden = true;
    updateFilters();
    return;
  }

  const featured = visible.filter((project) => project.featured);
  const rest = visible.filter((project) => !project.featured);

  projectsGrid.innerHTML = featured.map(projectCard).join("");
  projectsGrid.hidden = featured.length === 0;
  projectsGrid.classList.toggle("has-odd", featured.length % 2 === 1);

  if (projectsList && projectsListWrap) {
    projectsList.innerHTML = rest.map(projectRow).join("");
    projectsListWrap.hidden = rest.length === 0;
    if (projectsListTitle) {
      projectsListTitle.textContent =
        state.filter === "all" ? t("projects.more") : t("projects.list");
    }
  }

  updateFilters();
}

