function t(key) {
  return (I18N[state.lang] && I18N[state.lang][key]) || I18N.pt[key] || key;
}

function storeLang(lang) {
  try {
    localStorage.setItem("evf-lang", lang);
  } catch (error) {
    /* storage unavailable */
  }
}

function readLang() {
  try {
    const fromUrl = new URLSearchParams(window.location.search).get("lang");
    if (fromUrl === "en" || fromUrl === "pt") return fromUrl;
  } catch (error) {
    /* URL API unavailable */
  }

  try {
    return localStorage.getItem("evf-lang") === "en" ? "en" : "pt";
  } catch (error) {
    return "pt";
  }
}

function readStoredTheme() {
  try {
    const value = localStorage.getItem("evf-theme");
    return value === "light" || value === "dark" ? value : null;
  } catch (error) {
    return null;
  }
}

function storeTheme(theme) {
  try {
    localStorage.setItem("evf-theme", theme);
  } catch (error) {
    /* storage unavailable */
  }
}

function currentTheme() {
  return document.documentElement.dataset.theme === "dark" ? "dark" : "light";
}

function updateThemeUI() {
  const theme = currentTheme();
  const label = theme === "dark" ? t("theme.toLight") : t("theme.toDark");
  if (themeToggle) {
    themeToggle.setAttribute("aria-label", label);
    themeToggle.setAttribute("title", label);
  }
  if (themeColor) {
    themeColor.setAttribute("content", theme === "dark" ? "#0b0b0a" : "#f4f2ec");
  }
}

function applyTheme(theme, persist) {
  const next = theme === "dark" ? "dark" : "light";
  document.documentElement.dataset.theme = next;
  document.documentElement.style.colorScheme = next;
  if (persist) storeTheme(next);
  updateThemeUI();
  window.dispatchEvent(new Event("themechange"));
}

